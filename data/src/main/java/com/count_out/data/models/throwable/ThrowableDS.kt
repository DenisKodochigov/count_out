package com.count_out.data.models.throwable

sealed class ThrowableDS (private val t: Throwable?): Throwable(t){
    class TrainingThrow(t:Throwable): ThrowableDS(t)
    class ActivityThrow(t:Throwable): ThrowableDS(t)
    class WeatherTrow(t:Throwable): ThrowableDS(t)
    class RequestFailed(t:Throwable = Exception("return null")): ThrowableDS(t)
    class RequestNotCondition(t:Throwable = Exception("ResultData.flatMapCondition return null")): ThrowableDS(t)
    class ReturnNull(t:Throwable = Exception("return null")): ThrowableDS(t)
    class NotValidType(t:Throwable = Exception("not valid type")): ThrowableDS(t)
    class ErrorUpdate(t:Throwable = Exception("Update return 0")): ThrowableDS(t)
    class ErrorBleIsEmpty(t:Throwable = Exception("BleDataMapDb this.item.isEmpty")): ThrowableDS(t)
    class ErrorTypeBoolean(t:Throwable = Exception("Boolean false")): ThrowableDS(t)
    class ErrorTypeString(t:Throwable = Exception("String empty")): ThrowableDS(t)
    class ErrorTypeLong(t:Throwable = Exception("Long = 0")): ThrowableDS(t)
    class ErrorTypeWeather(t:Throwable = Exception("When getting weather, the type is not WeatherRequestDb.")): ThrowableDS(t)
    class ErrorTypePlan(t:Throwable = Exception("When getting Plan, the type is not PlanDb.")): ThrowableDS(t)
    class ErrorTypeSpeech(t:Throwable = Exception("When getting Speech, the type is not SpeechDb.")): ThrowableDS(t)
    class ErrorTypeSet(t:Throwable = Exception("When getting Set, the type is not SetDb.")): ThrowableDS(t)
    class ErrorTypePart(t:Throwable = Exception("When getting Part, the type is not PartDb.")): ThrowableDS(t)
    class ErrorTypeExercise(t:Throwable = Exception("When getting exercise, the type is not ExerciseDb.")): ThrowableDS(t)
    class ErrorTypeSetIdView(t:Throwable = Exception("When getting set, the type is not SetIdViewDb.")): ThrowableDS(t)
    class ErrorPlans(t:Throwable = Exception("List plans empty")): ThrowableDS(t)
    class ErrorSpeeches(t:Throwable = Exception("List speeches empty")): ThrowableDS(t)
    class ErrorExercises(t:Throwable = Exception("List exercises empty")): ThrowableDS(t)
    class ErrorActivities(t:Throwable = Exception("List activity empty")): ThrowableDS(t)
    class ErrorBleDeviceName(t:Throwable = Exception("List activity empty")): ThrowableDS(t)
    class ErrorBleSource(t:Throwable = Exception("Error convertor")): ThrowableDS(t)
    class ErrorSavePlan(t:Throwable = Exception("When saving the plan, the value is not long.")): ThrowableDS(t)
    class ErrorSaveSetting(t:Throwable = Exception("When saving the setting, the type is not SettingsDb.")): ThrowableDS(t)
    class ErrorSafeUse(t:Throwable = Exception("When executing safeUse, the type is not D.")): ThrowableDS(t)
    class ErrorSafeUseFlow(t:Throwable = Exception("When executing safeUseFlow, the type is not D.")): ThrowableDS(t)
    class ErrorSQl(t:Throwable): ThrowableDS(t)
    class UnknownThrow(t:Throwable): ThrowableDS(t)
    companion object {
        fun extract(t: Throwable): ThrowableDS = if (t is ThrowableDS) t else UnknownThrow(t)
    }
}